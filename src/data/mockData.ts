/** Build a synthetic acceptance row from a driver + trip, with optional extras. */
function buildAcceptance(
  id: string,
  tripId: string,
  driverIdx: number,
  extras: {
    applicantQuotedRatePerKm?: number;
    applicantMessage?: string;
    appliedMinAgo?: number;
  } = {},
): TripAcceptance {
  const d = mockDrivers[driverIdx]!;
  return {
    id,
    tripId,
    driverId: d.id,
    driver: {
      id: d.id,
      fullName: d.fullName,
      profilePhotoUrl: d.profilePhotoUrl,
      ratingAvg: d.ratingAvg,
      ratingCount: d.ratingCount,
      totalTripsCompleted: d.totalTripsCompleted,
      topTags: d.topTags,
      currentCity: d.currentCity,
    },
    vehicleId: d.vehicles[0]!.id,
    vehicle: {
      make: d.vehicles[0]!.make,
      model: d.vehicles[0]!.model,
      year: d.vehicles[0]!.year,
      carType: d.vehicles[0]!.carType,
      seats: d.vehicles[0]!.seats,
      ac: d.vehicles[0]!.ac,
    },
    status: 'applied',
    applicantQuotedRatePerKm: extras.applicantQuotedRatePerKm,
    applicantMessage: extras.applicantMessage,
    appliedAt: new Date(
      Date.now() - (extras.appliedMinAgo ?? 0) * 60_000,
    ).toISOString(),
  };
}

